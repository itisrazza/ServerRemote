#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""Embed the repository's GitHub contributors in the app.

Asks GitHub (through the `gh` CLI, so private forks work too) for the
contributors, most contributions first, skipping bots. Each one's avatar is
saved next to a generated Rust file listing them, which the app includes for
the About page's "Made by" row. Avatars of people no longer listed are removed.

Usage: scripts/fetch-contributors.py [owner/repo]
"""

import json
import subprocess
import sys
import urllib.request
from dataclasses import dataclass
from pathlib import Path

DEFAULT_REPO = "itisrazza/ServerRemote"
OUT_DIR = Path(__file__).resolve().parent.parent / "apps/server-remote/assets/contributors"
GENERATED = "generated.rs"
# Shown at 16pt, so this covers up to 4x displays.
AVATAR_SIZE = 64
EXTENSIONS = {"image/png": "png", "image/jpeg": "jpg"}


@dataclass(frozen=True)
class Contributor:
    login: str
    avatar_url: str


def fetch_contributors(repo: str) -> list[Contributor]:
    result = subprocess.run(
        ["gh", "api", "--paginate", f"repos/{repo}/contributors?per_page=100"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.exit(f"gh api failed for {repo} (exit {result.returncode}): {result.stderr.strip()}")
    # --paginate concatenates one JSON array per page.
    pages = json.JSONDecoder()
    entries: list[dict[str, object]] = []
    text, index = result.stdout.strip(), 0
    while index < len(text):
        page, index = pages.raw_decode(text, index)
        entries.extend(page)
        while index < len(text) and text[index].isspace():
            index += 1
    return [
        Contributor(login=str(entry["login"]), avatar_url=str(entry["avatar_url"]))
        for entry in entries
        if entry.get("type") == "User"
    ]


def download_avatar(contributor: Contributor) -> Path:
    separator = "&" if "?" in contributor.avatar_url else "?"
    url = f"{contributor.avatar_url}{separator}s={AVATAR_SIZE}"
    with urllib.request.urlopen(url) as response:
        content_type = response.headers.get_content_type()
        extension = EXTENSIONS.get(content_type)
        if extension is None:
            sys.exit(f"unexpected avatar type for {contributor.login}: {content_type} from {url}")
        path = OUT_DIR / f"{contributor.login}.{extension}"
        path.write_bytes(response.read())
    return path


def rust_source(avatars: list[tuple[Contributor, Path]]) -> str:
    entries = "".join(
        f'    Contributor {{\n        login: "{contributor.login}",\n'
        f'        avatar: include_bytes!("{path.name}"),\n    }},\n'
        for contributor, path in avatars
    )
    return (
        "// Generated by scripts/fetch-contributors.py; don't edit by hand.\n\n"
        "use super::Contributor;\n\n"
        f"pub const ALL: &[Contributor] = &[\n{entries}];\n"
    )


def main() -> None:
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    repo = sys.argv[1] if len(sys.argv) == 2 else DEFAULT_REPO
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    contributors = fetch_contributors(repo)
    if not contributors:
        sys.exit(f"{repo} has no contributors to list")
    avatars = [(contributor, download_avatar(contributor)) for contributor in contributors]

    kept = {path.name for _, path in avatars} | {GENERATED}
    for stale in (path for path in OUT_DIR.iterdir() if path.name not in kept):
        stale.unlink()
    generated = OUT_DIR / GENERATED
    generated.write_text(rust_source(avatars))
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2024", str(generated)], capture_output=True, text=True
    )
    if formatted.returncode != 0:
        sys.exit(f"rustfmt failed on {generated} (exit {formatted.returncode}): {formatted.stderr.strip()}")
    for contributor, path in avatars:
        print(contributor.login, path)


if __name__ == "__main__":
    main()
